/* SPDX-License-Identifier: MIT
 * Two Report Maps, chosen by the connected Bluetooth profile.
 *
 * Apple refuses a keyboard+Game Pad composite (the whole HID device is
 * invalidated), but Android/Windows accept it. One firmware therefore serves:
 *   profiles 0..2 (SAFE, 172B): keyboard/consumer/mouse + a vendor-defined
 *      9-byte ID4 report -- proven to keep iPad keypad/mouse alive.
 *   profile 3 (GAMEPAD, 209B): keyboard/consumer/mouse + a standard Game Pad
 *      ID4 report -- what Android needs for a working controller.
 *
 * Pair iPad/Mac/PC on slots 1-3, Android (or Windows) on slot 4. Report bodies
 * are 8/12/9/9 bytes in both maps. The unreachable LED output report is omitted
 * because the device exposes no Output Report characteristic.
 */
