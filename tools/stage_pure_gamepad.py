#!/usr/bin/env python3
"""Create a NEW, isolated diagnostic source profile; never build, push or flash.
The normal config is untouched. BLE keyboard/mouse are explicitly disabled in
this staged profile; USB, keys, settings, identity and physical board stay fixed.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BOARD = 'config/boards/arm/bbp9981'
TAP = BOARD + '/cmake/tap_extensions.cmake'
GAMEPAD = BOARD + '/cmake/gamepad.cmake'
OLD_PREFIX = '"-include" "${CMAKE_CURRENT_SOURCE_DIR}/custom_driver/trackpad_hog_snapshot.h"'
NEW_PREFIX = '"-include" "${CMAKE_CURRENT_SOURCE_DIR}/../../../../experiments/gamepad_protocol/pure_hog_guard.h"'
OLD_BLE = '''        # AFTER the existing mouse snapshot prefix. Tail attrs keep5/9/13.
        set_property(SOURCE "${APPLICATION_SOURCE_DIR}/src/hog.c"
            DIRECTORY "${APPLICATION_SOURCE_DIR}" APPEND PROPERTY COMPILE_OPTIONS
            "-include" "${CMAKE_CURRENT_SOURCE_DIR}/custom_driver/gamepad_ble_extension.h")'''
NEW_BLE = '''        # Isolated pure BLE profile: stock HIDS is unregistered by the tap prefix.
        zephyr_library_sources("${CMAKE_CURRENT_SOURCE_DIR}/../../../../experiments/gamepad_protocol/pure_runtime.c")'''
PRECONDITION = '''# Explicit diagnostic profile generated by tools/stage_pure_gamepad.py.
if(NOT CONFIG_BBP9981_GAMEPAD OR NOT CONFIG_ZMK_BLE OR
   NOT CONFIG_A320_TAP_OUTPUT OR NOT CONFIG_ZMK_POINTING)
    message(FATAL_ERROR "Pure BLE candidate requires gamepad/BLE/tap-output/pointing")
endif()
zephyr_compile_definitions(BBP9981_PURE_BLE_CANDIDATE=1)
'''

def digest(data):
    return hashlib.sha256(data).hexdigest()

def descriptor_digest(source):
    match = re.search(rb'bbp_exp_report_map\[\]\s*=\s*\{([^}]+)\}', source)
    if not match or not re.fullmatch(rb'\s*(?:0x[0-9a-fA-F]{2}\s*,\s*)+', match[1]):
        raise ValueError('descriptor must be the reviewed literal byte array')
    raw = bytes(int(x,16) for x in re.findall(rb'0x([0-9a-fA-F]{2})',match[1]))
    value = digest(raw)
    if len(raw)!=182 or value!='4317e34b66d9c247b0fb12327516c38c74deea04619db54a05cf190444482a3f':
        raise ValueError('descriptor changed: re-review before staging')
    return value

def stage(out):
    requested = Path(out).expanduser().absolute()
    if requested.is_symlink():
        raise ValueError('output itself must not be a symlink')
    target = requested.resolve()
    if target == ROOT or ROOT in target.parents or target in ROOT.parents:
        raise ValueError('stage must be outside the source tree and not its ancestor')
    if target.exists():
        raise FileExistsError('refusing to overwrite an existing stage: ' + str(target))
    sources = {}
    for directory in ['config', 'experiments/gamepad_protocol']:
        for path in sorted((ROOT/directory).rglob('*')):
            if path.is_symlink():
                raise ValueError('source symlink is not allowed: ' + str(path))
            if path.is_file():
                sources[path.relative_to(ROOT).as_posix()] = path.read_bytes()
    # Validate exact mechanical substitutions BEFORE creating any output.
    map_sha = descriptor_digest(sources['experiments/gamepad_protocol/stadia_descriptor.h'])
    tap = sources[TAP].decode('utf-8')
    gamepad = sources[GAMEPAD].decode('utf-8')
    if tap.count(OLD_PREFIX) != 1 or gamepad.count(OLD_BLE) != 1:
        raise ValueError('unrecognized board integration: refuse heuristic patching')
    modified = {
        TAP: tap.replace(OLD_PREFIX, NEW_PREFIX).encode('utf-8'),
        GAMEPAD: (PRECONDITION + gamepad.replace(OLD_BLE, NEW_BLE)).encode('utf-8'),
    }
    commit = subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    dirty = bool(subprocess.check_output(['git','status','--porcelain'],cwd=ROOT))
    print('Resolved NEW diagnostic stage:', target, flush=True)
    target.mkdir(parents=True, exist_ok=False)
    manifest = dict(schema=1, source_commit=commit, source_dirty=dirty,
                    build_performed=False, flashed=False, hardware_verified=False,
                    bluetooth_keyboard_mouse=False, bluetooth_gamepad='experimental',
                    usb_changed=False, identity_changed=False, keymap_changed=False,
                    report_map_sha256=map_sha,
                    modified_config=[], files={})
    for name, original in sources.items():
        data = modified.get(name, original)
        dest = target/name
        dest.parent.mkdir(parents=True,exist_ok=True)
        with dest.open('xb') as file:
            file.write(data)
        assert dest.read_bytes() == data
        manifest['files'][name] = dict(bytes=len(data),sha256=digest(data))
        if name in modified:
            manifest['modified_config'].append(dict(path=name, original_sha256=digest(original),
                                                    candidate_sha256=digest(data)))
        elif name.startswith('config/'):
            assert data == original
    with (target/'CANDIDATE.json').open('x') as file:
        json.dump(manifest,file,indent=2,ensure_ascii=False);file.write('\n')
    with (target/'README_CANDIDATE.md').open('x') as file:
        file.write('''# DIAGNOSTIC SOURCE PROFILE — NOT A FLASHABLE DELIVERY

BLE presents only the experimental Game Pad. BLE keyboard, consumer and mouse
entrypoints fail closed with ENOTSUP. USB and physical key mappings are unchanged.
Select the existing BLE endpoint and MEDIA layer using the existing controls.
No runtime personality switch, third-party VID/PID, bond deletion or settings
reset has been added. Host caching is not addressed by renaming this folder.

The old stock HOG table is retained only as a non-registered compilation object.
The pure service lives in a separate translation unit and has 16 attributes.
Before any release, verify the actual ELF iterable-service table, ARM ABI,
compiled DTS/config, UF2 identity, manuals, and all host/device acceptance gates.

Generating this directory performs NO build, upload, Actions, pairing or flash.
CANDIDATE.json records hashes and exactly two mechanical CMake substitutions.
Parent research and limitations: experiments/gamepad_protocol/README.md.
''')
    return manifest

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',required=True)
    parser.add_argument('--accept-ble-keymouse-disabled',action='store_true')
    args = parser.parse_args()
    if not args.accept_ble_keymouse_disabled:
        parser.error('explicit --accept-ble-keymouse-disabled is required; this is NOT the normal profile')
    stage(args.out)

if __name__ == '__main__':
    main()
